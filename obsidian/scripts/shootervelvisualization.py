import matplotlib.pyplot as plt
import matplotlib.image as mpimg
import numpy as np
from scipy.interpolate import interp1d

# 1. Load the background image
img = mpimg.imread('/content/field.png')

# 2. Define the Lookup Table (LUT)
distances = np.array([45, 115])
velocities = np.array([1250, 1500])

# Create the interpolation function
lut_func = interp1d(distances, velocities, kind='linear', fill_value='extrapolate')

# 3. Setup the plot
fig, ax = plt.subplots(figsize=(10, 10))

# Display image with extent matching (0,0) bottom-left to (144,144) top-right
ax.imshow(img, extent=[0, 144, 0, 144])

# Target point
target_x, target_y = 15, 128
ax.plot(target_x, target_y, 'rx', markersize=12, markeredgewidth=3, label='Target (15, 128)')

# 4. Generate circles representing the LUT distances
# Now the radius of the circle is equal to the distance 'd'


for d in distances:
    vel = float(lut_func(d))
    # Radius is now the distance d
    circle = plt.Circle((target_x, target_y), d, color='lime', fill=False,
                        linestyle='--', linewidth=2, alpha=0.7,
                        label=f'Dist: {d}, Vel: {vel:.0f}')
    ax.add_patch(circle)

ax.set_xlim(0, 144)
ax.set_ylim(0, 144)
ax.set_xlabel('X Coordinate')
ax.set_ylabel('Y Coordinate')
ax.set_title('Shooter Velocity Lookup Table (Radius = Distance)')
ax.legend(loc='upper right')
plt.grid(True, alpha=0.3)
plt.show()

