import matplotlib.patches as mpatches

# Loop through each CSV file found and create a combined time-velocity and time-target graph
for file in csv_files:
    print(f"\nProcessing file for plotting: {file}")
    df = pd.read_csv(file)

    # Remove rows where 'shooter_target' is 0
    df_filtered = df[df['shooter_target'] != 0].copy() # Use .copy() to avoid SettingWithCopyWarning

    # Calculate 'ready' status based on the formula: abs(target_velocity - current_velocity) < 70
    df_filtered['ready'] = abs(df_filtered['shooter_target'] - df_filtered['shooter_velocity']) < 70

    # Normalize time by subtracting the first time value, using .iloc[0] for positional access
    df_filtered["time"] = df_filtered["time"] - df_filtered["time"].min()

    # Calculate instantaneous difference (overshoot potential)
    df_filtered['velocity_diff'] = df_filtered['shooter_velocity'] - df_filtered['shooter_target']

    max_overshoot_value = 0
    time_at_max_overshoot = None
    target_at_max_overshoot = None
    velocity_at_max_overshoot = None

    # Find actual overshoot (where velocity > target) and its peak
    overshoot_data = df_filtered[df_filtered['velocity_diff'] > 0]
    if not overshoot_data.empty:
        max_overshoot_value = overshoot_data['velocity_diff'].max()
        # Find the time corresponding to this maximum overshoot
        idx_max_overshoot = overshoot_data['velocity_diff'].idxmax()
        time_at_max_overshoot = overshoot_data.loc[idx_max_overshoot, 'time']
        target_at_max_overshoot = overshoot_data.loc[idx_max_overshoot, 'shooter_target']
        velocity_at_max_overshoot = overshoot_data.loc[idx_max_overshoot, 'shooter_velocity']

        print(f"Max overshoot value for {os.path.basename(file)}: {max_overshoot_value:.2f} at time {time_at_max_overshoot:.2f}")
    else:
        print(f"No positive overshoot found for {os.path.basename(file)}.")

    # Correctly filter for non-ready times
    non_ready_times = df_filtered[~df_filtered['ready']]["time"]

    settle_time_value = None
    # Calculate settle_time only if there are non_ready_times
    if not non_ready_times.empty:
        settle_time_value = non_ready_times.max() - non_ready_times.min()
        print(f"Settle time for {os.path.basename(file)}: {settle_time_value:.2f}")
    else:
        print(f"No 'non-ready' periods found for {os.path.basename(file)}.")

    plt.figure(figsize=(12, 7))
    ax = plt.gca() # Get current axes for axvspan

    sns.lineplot(x='time', y='shooter_velocity', data=df_filtered, label='Shooter Velocity', ax=ax)
    sns.lineplot(x='time', y='shooter_target', data=df_filtered, label='Shooter Target', ax=ax)

    # Add vertical colored rows
    current_status = None
    segment_start_time = None

    for index, row in df_filtered.iterrows():
        time = row['time']
        ready_status = row['ready']

        if segment_start_time is None: # First data point
            current_status = ready_status
            segment_start_time = time
        elif ready_status != current_status: # Status changed, draw previous segment
            color = 'green' if current_status else 'red'
            ax.axvspan(segment_start_time, time, color=color, alpha=0.1, lw=0)
            current_status = ready_status
            segment_start_time = time

    # Draw the last segment
    if segment_start_time is not None:
        color = 'green' if current_status else 'red'
        ax.axvspan(segment_start_time, df_filtered['time'].iloc[-1], color=color, alpha=0.1, lw=0)

    # Add settle time line if calculated
    if settle_time_value is not None:
        ax.axvline(x=settle_time_value, color='purple', linestyle='--', label=f'Settle Time: {settle_time_value:.2f}')

    # Add max overshoot line if calculated
    if time_at_max_overshoot is not None and target_at_max_overshoot is not None and velocity_at_max_overshoot is not None:
        ax.vlines(x=time_at_max_overshoot, ymin=target_at_max_overshoot, ymax=velocity_at_max_overshoot,
                  color='black', linestyle=':', linewidth=2, label=f'Max Overshoot ({max_overshoot_value:.2f})')

    # Create custom legend handles for the colored regions
    ready_patch = mpatches.Patch(color='green', alpha=0.1, label='Shooter Ready')
    not_ready_patch = mpatches.Patch(color='red', alpha=0.1, label='Shooter Not Ready')

    handles, labels = ax.get_legend_handles_labels()
    handles.extend([ready_patch, not_ready_patch])

    plt.title(f'Time vs Shooter Velocity and Target for {os.path.basename(file)} (Excluding Shooter Target = 0)')
    plt.xlabel('Time')
    plt.ylabel('Value')
    plt.legend(handles=handles, loc='upper right')
    plt.grid(True)

    # Save the plot with a descriptive filename and high DPI
    plot_filename = f"individual_{os.path.splitext(os.path.basename(file))[0]}.png"
    plt.savefig(plot_filename, dpi=500, bbox_inches='tight')
    print(f"Saved individual plot as {plot_filename}")
    plt.show()

